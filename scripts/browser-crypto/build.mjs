import { build } from 'esbuild';
import { readFile, writeFile, mkdir, copyFile, mkdtemp, rm } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
const here = fileURLToPath(new URL('.', import.meta.url));
const vendor = new URL('../../ui/vendor/', import.meta.url);
// --check rebuilds into a temporary directory and compares every generated
// byte with the committed assets, so a hand-edited bundle with a regenerated
// noble.sha256 is caught. Run after `pnpm install --frozen-lockfile`.
const check = process.argv.includes('--check');
const temporary = check ? await mkdtemp(join(tmpdir(), 'hashstash-noble-')) : null;
const out = check ? pathToFileURL(temporary + '/') : vendor;
await mkdir(out, { recursive: true });
await build({ absWorkingDir: here, entryPoints: ['entry.js'], outfile: fileURLToPath(new URL('noble.js', out)), bundle: true, format: 'iife', globalName: 'HashstashNoble', platform: 'browser', target: ['es2022'], minify: false, legalComments: 'inline', banner: {js:'// Generated by scripts/browser-crypto/build.mjs. Pinned noble-curves/hashes 2.4.0; MIT.'} });
for (const name of ['curves', 'hashes']) await copyFile(new URL(`node_modules/@noble/${name}/LICENSE`, import.meta.url), new URL(`noble-${name}.LICENSE`, out));
const bytes = await readFile(new URL('noble.js', out));
await writeFile(new URL('noble.sha256', out), createHash('sha256').update(bytes).digest('hex') + '  noble.js\n');
if (check) {
  const different = [];
  for (const name of ['noble.js', 'noble.sha256', 'noble-curves.LICENSE', 'noble-hashes.LICENSE'])
    if (!(await readFile(new URL(name, out))).equals(await readFile(new URL(name, vendor)))) different.push(name);
  await rm(temporary, { recursive: true, force: true });
  if (different.length) { console.error(`Committed ui/vendor differs from a clean build: ${different.join(', ')}`); process.exit(1); }
  console.log(`Committed cryptography bundle matches a clean build (${bytes.length} bytes).`);
} else console.log(`Built local cryptography bundle (${bytes.length} bytes).`);
