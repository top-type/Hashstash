'use strict';
// ui/vendor/noble.js is compiled into the node binary and served to every
// wallet. build.mjs rewrites noble.sha256 from whatever it just produced, so
// that file alone cannot reveal an edited bundle. PINNED is a reviewed record
// kept apart from the build output: any bundle change must also change this
// line. To reproduce the bundle from the lockfile, run
// `corepack pnpm install --frozen-lockfile && corepack pnpm run check` in
// scripts/browser-crypto; continuous integration runs it on every push.
const assert = require('node:assert/strict');
const fs = require('node:fs'), path = require('node:path'), { createHash } = require('node:crypto');
const PINNED = 'deba70770f9b3a145da6768bcfa6bdc99565dd71118015dcee9f886c2a378695';
const root = path.join(__dirname, '..'), read = file => fs.readFileSync(path.join(root, file));
let checks = 0;
const eq = (a, b, m) => { assert.deepEqual(a, b, m); checks++; }, ok = (v, m) => { assert.ok(v, m); checks++; };

const bundle = read('ui/vendor/noble.js'), text = bundle.toString('utf8');
eq(createHash('sha256').update(bundle).digest('hex'), PINNED, 'the served bundle is the reviewed one');
eq(read('ui/vendor/noble.sha256').toString('utf8'), `${PINNED}  noble.js\n`, 'the generated checksum file agrees with the pin');
ok(text.startsWith('// Generated by scripts/browser-crypto/build.mjs. Pinned noble-curves/hashes 2.4.0; MIT.\n'), 'the bundle names its pinned sources');
for (const api of [/\bfetch\s*\(/, /XMLHttpRequest/, /WebSocket/, /\beval\s*\(/, /new\s+Function\b/, /importScripts/, /sendBeacon/, /localStorage|sessionStorage|indexedDB/, /\bimport\s*\(/, /document\./])
  ok(!api.test(text), `the cryptography bundle uses no network, storage, DOM or dynamic code API: ${api}`);

const manifest = JSON.parse(read('scripts/browser-crypto/package.json'));
eq(manifest.dependencies, { '@noble/curves': '2.4.0', '@noble/hashes': '2.4.0' }, 'library versions are exact');
eq(manifest.devDependencies, { esbuild: '0.28.2' }, 'the bundler version is exact');
eq(manifest.scripts.check, 'node build.mjs --check', 'a byte-for-byte rebuild check is available');
// Continuous integration runs the rebuild check with this pnpm, which
// corepack downloads only when its tarball matches the hash.
ok(/^pnpm@\d+\.\d+\.\d+\+sha512\.[0-9a-f]{128}$/.test(manifest.packageManager || ''), 'the package manager version and tarball hash are exact');
const lock = read('scripts/browser-crypto/pnpm-lock.yaml').toString('utf8');
for (const name of ['@noble/curves@2.4.0', '@noble/hashes@2.4.0', 'esbuild@0.28.2']) {
  const entry = new RegExp(`\\n  '?${name.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&')}'?:\\n    resolution: \\{integrity: sha512-[A-Za-z0-9+/=]{88}\\}`);
  ok(entry.test(lock), `${name} is locked with a registry integrity hash`);
}
const builder = read('scripts/browser-crypto/build.mjs').toString('utf8');
ok(builder.includes("process.argv.includes('--check')") && builder.includes('.equals('), 'the build script compares a clean rebuild with the committed assets');
console.log(`Vendor integrity: ${checks} checks passed.`);
