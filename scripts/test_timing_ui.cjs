'use strict';
const assert = require('node:assert/strict');
const { setup } = require('./test_outcome_wallet.cjs');

async function run() {
  let checks = 0;
  const equal = (actual, expected, message) => { assert.equal(actual, expected, message); checks++; };
  const match = (actual, expected, message) => { assert.match(actual, expected, message); checks++; };
  const h = await setup(), s = h.currentSnapshot;
  const decision = s.governance.phase.Governance;
  decision.started = 180; decision.started_height = 12; decision.blocks = 40; decision.leading_blocks = 5;
  Object.assign(s.status.settings, {lead:60,rest:480,decision_blocks:40});
  for (const [interval,countdown] of [[1,'32s'],[7,'3m 44s'],[15,'8m 0s'],[30,'16m 0s'],[60,'32m 0s']]) {
    s.status.settings.interval = interval;
    s.governance.frozen = {...s.status.settings};
    await h.refresh(); await h.navigate('#governance');
    equal(h.get('gov-countdown').textContent, '32 blocks', 'target interval cannot change the remaining decision blocks');
    equal(h.get('gov-progress').value, 20, 'eight of forty blocks observed');
    equal(h.get('network-phase-progress').value, 20);
    equal(h.get('timing-governance').textContent, '40 blocks');
    equal(h.get('timing-rest').textContent, '8m 0s');
    equal(h.get('network-clock').textContent, '5m 0s');
    match(h.get('network-phase').title, new RegExp(`^32 blocks at the ${interval}s target`));
    match(h.get('gov-countdown').title, new RegExp(`^~${countdown}`));
    match(h.get('gov-result').title, /8 blocks observed/);
  }
  s.status.settings.interval = 15; s.governance.frozen = { ...s.status.settings };
  s.governance.phase = { Rest: { until: 780, pending: ['Interval',30] } }; s.governance.pass = s.pass = s.fail = null;
  await h.refresh();
  match(h.get('gov-subtitle').textContent, /30s after rest/);
  match(h.get('network-phase').title, /^32 blocks at the 15s target/, 'pending interval cannot alter an active rest schedule');
  s.status.clock = s.governance.clock = 780; s.status.settings.interval = 30;
  s.governance.frozen = { ...s.status.settings };
  s.governance.phase = { Auction: { round:1,opened:780,leader:'ab'.repeat(32),lead_since:780 } };
  await h.refresh();
  equal(h.get('gov-countdown').textContent, '2 blocks');
  match(h.get('network-phase').title, /^2 blocks at the 30s target/);
  equal(h.get('gov-subtitle').textContent, 'The leading proposal advances after its required lead.');
  // The timeout leaves at least one full observation beyond the required lead.
  s.config.auction_timeout = 20; s.status.settings.lead = s.governance.frozen.lead = 61;
  s.governance.phase.Auction.leader = null;
  await h.refresh();
  equal(h.get('timing-auction').textContent, '1m 1s lead · 1m 31s limit');
  equal(h.get('gov-countdown').textContent, '4 blocks', 'ceil division handles policy durations not divisible by the interval');
  const form = h.get('propose-form');
  form.elements.type.value = 'parameter'; form.elements.parameter.value = 'DecisionBlocks'; form.elements.parameter_value.value = '1200';
  await h.get('proposal-parameter').fire('change');
  equal(h.get('parameter-preview').textContent, '40 blocks → 1,200 blocks');
  form.elements.parameter.value = 'Interval'; form.elements.parameter_value.value = '15';
  await h.get('proposal-parameter').fire('change');
  match(h.get('parameter-preview').title, /after rest if approved/);
  equal(h.get('wallet-expiry').value, '2', 'signed transaction expiry keeps its explicit block-count policy');
  s.status.height = s.status.clock = s.governance.clock = 0;
  s.status.settings.interval = 15; s.governance.frozen = { ...s.status.settings };
  s.governance.phase = { Rest:{ until:480,pending:null } };
  await h.refresh();
  equal(h.get('network-phase-label').textContent, 'Rest');
  match(h.get('network-phase-time').textContent, /^32 blocks remaining/);
  match(h.get('network-phase').title, /^32 blocks at the 15s target/);
  equal(h.get('network-phase-progress').value, 0, 'genesis begins with an empty phase bar');
  equal(h.get('network-phase-progress').hidden, false);
  match(h.get('network-phase-progress')['aria-valuetext'], /0 blocks completed of 32\. 32 blocks to next auction\. Block 0\./, 'exact phase and height stay accessible');
  await h.refresh();
  equal(h.get('network-phase-progress').value, 0, 'refresh without another block never advances the bar');
  s.status.height = 1; s.status.clock = s.governance.clock = 15;
  await h.refresh();
  equal(h.get('network-phase-progress').value, 3.12, 'one of 32 blocks advances the phase');
  s.status.height = 0; s.status.clock = s.governance.clock = 0;
  await h.refresh();
  equal(h.get('network-phase-progress').value, 0, 'a reorg replaces progress with the canonical snapshot');
  s.status.settings.interval = 30;
  s.governance.frozen = { ...s.status.settings, lead:61 };
  s.governance.phase = { Auction:{ opened:0,leader:'ab'.repeat(32),lead_since:0 } };
  s.config.auction_timeout = 120;
  await h.refresh();
  equal(h.get('network-phase-progress').value, 0);
  s.status.height = 1; s.status.clock = s.governance.clock = 30;
  await h.refresh();
  equal(h.get('network-phase-progress').value, 33.33, 'a 61-second lead at a 30-second interval spans three blocks');
  s.status.height = 2; s.status.clock = s.governance.clock = 60;
  await h.refresh();
  equal(h.get('network-phase-progress').value, 66.66);
  s.governance.phase.Auction.lead_since = 60;
  await h.refresh();
  equal(h.get('network-phase-progress').value, 50, 'when a new lead cannot finish before timeout, progress follows the timeout');
  s.governance.phase.Auction.opened = 60;
  await h.refresh();
  equal(h.get('network-phase-progress').value, 0, 'a fresh eligible lead starts its own schedule');
  h.handlers.snapshot = () => ({ ok:false,status:503 });
  await h.refresh();
  equal(h.get('network-phase-progress').hidden, true, 'unavailable snapshots hide progress rather than imply zero');
  equal(h.get('network-phase-progress')['aria-valuetext'], undefined, 'unavailable snapshots do not retain stale progress details');
  equal(h.wallet.length, 0, 'timing views never broadcast');
  console.log(`Scheduled-time UI: ${checks} behavior checks passed`);
}
run().catch(error => { console.error(error); process.exitCode = 1; });
